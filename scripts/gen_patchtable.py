#!/usr/bin/env python3
"""gen_patchtable.py - emit installer/PatchTable.cs from dockfix_patch.py so the installer and
the Python tool always carry the same byte table.

Usage: python -I gen_patchtable.py <out.cs> [version]
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import dockfix_patch as dp   # noqa: E402


def main(argv):
    out = argv[1] if len(argv) > 1 else os.path.join(HERE, "..", "installer", "PatchTable.cs")
    version = argv[2] if len(argv) > 2 else "1.0.0"
    lines = []
    lines.append("// GENERATED by scripts/gen_patchtable.py from scripts/dockfix_patch.py - do not edit.")
    lines.append("namespace HW1ClassicFix {")
    lines.append("public static class PatchTable {")
    lines.append("    public const int PeSize = %d;" % dp.PE_SIZE)
    lines.append('    public const string OriginalSha256 = "%s";' % dp.ORIGINAL_SHA256)
    lines.append('    public const string Version = "%s";' % version)
    lines.append("    public static readonly Site[] Sites = new Site[] {")
    n = 0
    for group, patches in dp.GROUPS:
        for va, old, new, note in patches:
            legacy = dp.LEGACY.get(va, [])
            leg = "null" if not legacy else "new string[] { %s }" % ", ".join('"%s"' % dp.hx(b).hex() for b in legacy)
            lines.append('        new Site(0x%x, "%s", "%s", "%s", "%s", %s),' % (
                va, dp.hx(old).hex(), dp.hx(new).hex(), group, note.replace('"', "'"), leg))
            n += 1
    lines.append("    };")
    lines.append("}")
    lines.append("}")
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d sites, version %s" % (out, n, version))


if __name__ == "__main__":
    main(sys.argv)
